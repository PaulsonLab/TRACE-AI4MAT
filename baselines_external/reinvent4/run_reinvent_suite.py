def normalize_oracles(raw_oracles: List[str]) -> List[str]:
    aliases = {
        "all": "all",
        "plogp": "penalized_logp",
        "penalized-logp": "penalized_logp",
        "penalized_logp": "penalized_logp",
        "qed": "qed",
        "median2": "median_2",
        "median_2": "median_2",
        "osimertinib": "osimertinib_mpo",
        "osimertinib_mpo": "osimertinib_mpo",
        "scaffold": "scaffold_hop",
        "scaffold_hop": "scaffold_hop",
        "drd2": "drd2",
        "drd2_activity": "drd2",
        "deco": "deco_hop",
        "deco_hop": "deco_hop",
        "decoration_hop": "deco_hop",
        "jnk3": "jnk3",
        "jnk3_activity": "jnk3",
    }
    out: List[str] = []
    for raw in raw_oracles:
        key = raw.strip().lower().replace(" ", "_")
        if key not in aliases:
            raise ValueError(f"Unknown oracle '{raw}'. Use all or one of: {', '.join(ORACLE_ORDER)}")
        value = aliases[key]
        if value == "all":
            return ORACLE_ORDER[:]
        if value not in out:
            out.append(value)
    return out


def command_text(cmd: List[str]) -> str:
    return " ".join(f'"{part}"' if " " in str(part) else str(part) for part in cmd)


def run_streamed(cmd: List[str], cwd: Path, log_path: Path, env: Dict[str, str], dry_run: bool) -> int:
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with open(log_path, "w", encoding="utf-8", errors="replace") as log:
        log.write(f"cwd: {cwd}\n")
        log.write(f"command: {command_text(cmd)}\n\n")
        if dry_run:
            print(f"[dry-run] {command_text(cmd)}")
            return 0
        print(f"[exec] {command_text(cmd)}")
        proc = subprocess.Popen(
            cmd,
            cwd=str(cwd),
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )
        assert proc.stdout is not None
        for line in proc.stdout:
            print(line, end="")
            log.write(line)
        return int(proc.wait())


def build_reinvent_config(
    oracle: str,
    seed: int,
    run_dir: Path,
    prior_file: Path,
    agent_file: Path,
    device: str,
    n_iters: int,
    batch_size: int,
    cfg: Dict[str, Any],
) -> str:
    prefix = f"reinvent4_{oracle}_seed_{seed}"
    return f'''# Auto-generated by reinvent4_oracle_suite/run_reinvent_suite.py
run_type = "staged_learning"
device = "{device}"
tb_logdir = "{(run_dir / 'tb_logs').as_posix()}"
json_out_config = "{(run_dir / (prefix + '_config.json')).as_posix()}"

[parameters]
summary_csv_prefix = "{(run_dir / prefix).as_posix()}"
use_checkpoint = false
purge_memories = false
prior_file = "{prior_file.as_posix()}"
agent_file = "{agent_file.as_posix()}"
batch_size = {int(batch_size)}
unique_sequences = true
randomize_smiles = true
tb_isim = false

[learning_strategy]
type = "dap"
sigma = 128
rate = 0.0001

[[stage]]
chkpt_file = "{(run_dir / (prefix + '.chkpt')).as_posix()}"
termination = "simple"
max_score = 1.0
min_steps = {int(n_iters)}
max_steps = {int(n_iters)}

[stage.scoring]
type = "arithmetic_mean"

[[stage.scoring.component]]
[stage.scoring.component.TraceOracleReward]

[[stage.scoring.component.TraceOracleReward.endpoint]]
name = "TRACE {oracle} reward"
weight = 1.0

[stage.scoring.component.TraceOracleReward.endpoint.params]
oracle_name = "{oracle}"
reward_low = {float(cfg["reward_low"])}
reward_high = {float(cfg["reward_high"])}
max_sa_score = {float(cfg["max_sa"])}
max_smiles_length = {int(cfg["max_smiles_length"])}
max_heavy_atoms = {int(cfg["max_heavy_atoms"])}
'''


def find_reinvent_csv(run_dir: Path, oracle: str, seed: int) -> Optional[Path]:
    prefix = f"reinvent4_{oracle}_seed_{seed}"
    candidates = sorted(run_dir.glob(f"{prefix}*.csv"), key=lambda path: path.stat().st_mtime, reverse=True)
    return candidates[0] if candidates else None


def install_plugin(suite_root: Path, reinvent_root: Path) -> Path:
    source = suite_root / "reinvent_plugins" / "components" / "comp_trace_oracles.py"
    target = Path(reinvent_root).expanduser().resolve() / "reinvent_plugins" / "components" / "comp_trace_oracles.py"
    if not source.exists():
        raise FileNotFoundError(f"Missing plugin source: {source}")
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)
    return target


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run REINVENT4 on the six TRACE benchmark oracles.")
    parser.add_argument("--out-root", default="benchmark_reinvent4_1k")
    parser.add_argument("--oracles", nargs="+", default=["all"])
    parser.add_argument("--seeds", nargs="*", type=int, default=[11, 22, 33, 44, 55])
    parser.add_argument("--initial-root", default="initial_data")
    parser.add_argument("--n-initial", type=int, default=20)
    parser.add_argument("--n-iters", type=int, default=20)
    parser.add_argument("--batch-size", type=int, default=49)
    parser.add_argument("--max-oracle-calls", type=int, default=1000)
    parser.add_argument("--device", default="cuda", choices=["cuda", "cpu", "mps", "xpu"])
    parser.add_argument("--prior-file", required=True)
    parser.add_argument("--agent-file", default=None)
    parser.add_argument("--reinvent-root", default=None, help="Optional REINVENT4 checkout root; copies the TRACE plugin into it.")
    parser.add_argument("--reinvent-command", nargs="+", default=["reinvent"])
    parser.add_argument("--skip-existing", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--smoke", action="store_true", help="One seed, two fixed REINVENT steps, small batch.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    suite_root = Path(__file__).resolve().parent
    out_root = Path(args.out_root).expanduser().resolve()
    initial_root = Path(args.initial_root)
    if not initial_root.is_absolute():
        initial_root = suite_root / initial_root
    prior_file = Path(args.prior_file).expanduser().resolve()
    agent_file = Path(args.agent_file).expanduser().resolve() if args.agent_file else prior_file
    oracles = normalize_oracles(args.oracles)
    seeds = [int(seed) for seed in args.seeds]
    n_iters = int(args.n_iters)
    batch_size = int(args.batch_size)
    n_initial = int(args.n_initial)
    max_oracle_calls = int(args.max_oracle_calls)
    if args.smoke:
        seeds = [seeds[0] if seeds else 11]
        n_iters = 2
        batch_size = 8
        n_initial = min(n_initial, 3)
        max_oracle_calls = n_initial + n_iters * batch_size

    out_root.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["TRACE_REINVENT_SUITE_ROOT"] = str(suite_root)
    env["PYTHONPATH"] = str(suite_root) + os.pathsep + env.get("PYTHONPATH", "")
    plugin_target = None
    if args.reinvent_root:
        plugin_target = install_plugin(suite_root, Path(args.reinvent_root))
        print(f"[plugin] copied TRACE plugin to {plugin_target}")

    suite_manifest: Dict[str, Any] = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "suite_root": str(suite_root),
        "out_root": str(out_root),
        "python": sys.version.replace("\n", " "),
        "platform": platform.platform(),
        "oracles": oracles,
        "method": "reinvent4_external",
        "seeds": seeds,
        "n_initial": n_initial,
        "n_iters": n_iters,
        "batch_size": batch_size,
        "max_oracle_calls": max_oracle_calls,
        "device": args.device,
        "prior_file": str(prior_file),
        "agent_file": str(agent_file),
        "reinvent_root": str(Path(args.reinvent_root).expanduser().resolve()) if args.reinvent_root else None,
        "plugin_installed_to": str(plugin_target) if plugin_target else None,
        "fixed_step_policy": (
            "All REINVENT runs use exactly n_iters fixed staged-learning steps. "
            "Invalid, duplicate, or constraint-failing generated molecules are saved in generated_samples CSVs "
            "but do not consume unique valid oracle budget."
        ),
        "runs": [],
    }
    manifest_path = out_root / ("suite_manifest.dry_run.json" if args.dry_run else "suite_manifest.json")
    write_json(manifest_path, suite_manifest)

    for oracle in oracles:
        cfg = ORACLE_CONFIGS[oracle]
        oracle_out = out_root / oracle
        method_root = oracle_out / "reinvent4_external"
        expected_budget = max_oracle_calls
        for seed in seeds:
            run_dir = method_root / f"seed_{seed}" / "reinvent_run"
            summary_path = method_root / f"seed_{seed}" / f"summary_seed_{seed}.json"
            if args.skip_existing and summary_path.exists():
                print(f"[skip] {oracle}/seed_{seed}: {summary_path}")
                continue
            run_dir.mkdir(parents=True, exist_ok=True)
            config_text = build_reinvent_config(
                oracle=oracle,
                seed=seed,
                run_dir=run_dir,
                prior_file=prior_file,
                agent_file=agent_file,
                device=args.device,
                n_iters=n_iters,
                batch_size=batch_size,
                cfg=cfg,
            )
            config_path = run_dir / f"reinvent4_{oracle}_seed_{seed}.toml"
            config_path.write_text(config_text, encoding="utf-8")
            log_path = run_dir / f"reinvent4_{oracle}_seed_{seed}.log"
            cmd = [*args.reinvent_command, "-l", str(log_path), str(config_path)]
            run_record = {
                "oracle": oracle,
                "seed": seed,
                "config": str(config_path),
                "log": str(log_path),
                "command": cmd,
                "status": "planned",
            }
            rc = run_streamed(cmd, cwd=run_dir, log_path=run_dir / "launcher_stdout.log", env=env, dry_run=args.dry_run)
            if rc != 0:
                run_record["status"] = "reinvent_failed"
                run_record["return_code"] = rc
                suite_manifest["runs"].append(run_record)
                write_json(manifest_path, suite_manifest)
                raise SystemExit(rc)
            if args.dry_run:
                run_record["status"] = "dry_run"
                suite_manifest["runs"].append(run_record)
                write_json(manifest_path, suite_manifest)
                continue

            csv_path = find_reinvent_csv(run_dir, oracle, seed)
            if csv_path is None:
                run_record["status"] = "missing_reinvent_csv"
                suite_manifest["runs"].append(run_record)
                write_json(manifest_path, suite_manifest)
                raise FileNotFoundError(f"No REINVENT CSV found in {run_dir}")

            constraints = MoleculeConstraints(
                max_sa_score=float(cfg["max_sa"]),
                max_smiles_length=int(cfg["max_smiles_length"]),
                max_heavy_atoms=int(cfg["max_heavy_atoms"]),
            )
            evaluate_reinvent_csv(
                csv_path=csv_path,
                out_root=method_root,
                oracle_name=oracle,
                seed=seed,
                max_oracle_calls=max_oracle_calls,
                constraints=constraints,
                n_iters=n_iters,
                batch_size=batch_size,
                initial_data=initial_root / oracle,
                n_initial=n_initial,
            )
            run_record["status"] = "complete"
            run_record["reinvent_csv"] = str(csv_path)
            run_record["summary"] = str(summary_path)
            suite_manifest["runs"].append(run_record)
            write_json(manifest_path, suite_manifest)

        if not args.dry_run:
            spec = get_oracle_spec(oracle)
            aggregate_oracle(
                oracle_out=oracle_out,
                method="reinvent4_external",
                expected_budget_by_seed={seed: expected_budget for seed in seeds},
                n_iters=n_iters,
                objective_name=spec.display_name,
                reward_label=spec.reward_label,
            )

    if not args.dry_run:
        aggregate_suite(out_root, oracles)
        suite_manifest["completed_at_utc"] = datetime.now(timezone.utc).isoformat()
        suite_manifest["suite_outputs"] = {
            "comparison_by_method": str(out_root / "suite_comparison_by_method.csv"),
            "rank_by_oracle": str(out_root / "suite_method_rank_by_oracle.csv"),
        }
        write_json(manifest_path, suite_manifest)
    print(f"[suite complete] {out_root}")


if __name__ == "__main__":
    main()
